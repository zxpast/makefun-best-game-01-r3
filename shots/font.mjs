const BLANK = ['.....', '.....', '.....', '.....', '.....', '.....', '.....'];

export function glyph(ch) {
  if (ch >= 'a' && ch <= 'z') ch = ch.toUpperCase();
  return G[ch] || BLANK;
}

export function textWidth(text) {
  return text.length * 6 - 1;
}
